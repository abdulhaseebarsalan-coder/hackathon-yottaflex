"""MySQL DDL and seed export, generated from orchestrator.schema (the DDL can never drift from it).

Load order (scripts/load_mysql.py does this):
  1. sql/schema.sql                  DROP + CREATE every table: PKs, inline FKs, UNIQUE, CHECK, indexes
  2. output/<scale>/sql/seed.sql     INSERTs in dependency order, one transaction
  3. sql/deferred_constraints.sql    the forward-reference FKs (schema.deferred_foreign_keys());
                                     MySQL validates every loaded row when they are added

CHECK constraints cover enums and structural rules only. Business-rule ordering (e.g. approval before
provisioning) is deliberately NOT a constraint: the published dataset contains labelled anomalies
that must load so they can be detected in SQL.
"""

from __future__ import annotations

from datetime import date, datetime
from typing import Any

from orchestrator.schema import TABLES, deferred_foreign_keys, inline_foreign_keys

HEADER = "-- Generated by orchestrator.export.sql_writer from src/orchestrator/schema.py. Do not edit by hand.\n"
INSERT_BATCH = 500
MAX_IDENT = 64

SQL_TYPE = {"int": "INT", "decimal": "DECIMAL(12,2)", "bool": "BOOLEAN", "date": "DATE", "datetime": "DATETIME"}

# Extra (non-FK) indexes for the queries in sql/queries/. InnoDB indexes FK columns automatically.
INDEXES = {
    "employee": [("employment_status",)],
    "task": [("task_status",), ("task_code",)],
    "access_grant": [("grant_status",), ("employee_id", "access_role_id")],
    "asset": [("asset_status",)],
    "asset_assignment": [("asset_id", "returned_date")],
    "audit_event": [("entity_type", "entity_id"), ("event_type",), ("event_timestamp",)],
}

# Structural CHECKs beyond enums (never violated by injected anomalies).
TABLE_CHECKS = {
    "task": [("one_case", "(`onboarding_case_id` IS NULL) <> (`offboarding_case_id` IS NULL)"),
             ("seq_positive", "`task_seq` >= 1")],
    "task_dependency": [("not_self", "`task_id` <> `depends_on_task_id`")],
    "asset": [("cost_positive", "`purchase_cost` > 0")],
    "onboarding_case": [("pct_range", "`completion_pct` BETWEEN 0 AND 100")],
}


def q(name: str) -> str:
    return f"`{name}`"


def ident(*parts: str) -> str:
    name = "_".join(parts)
    return name if len(name) <= MAX_IDENT else name[:MAX_IDENT]


def _sql_comment(text: str) -> str:
    return text.replace("\\", "\\\\").replace("'", "''")


def column_type(f) -> str:
    return f"VARCHAR({f.length})" if f.type == "str" else SQL_TYPE[f.type]


def build_schema_sql() -> str:
    deferred = {(c, col) for c, col, _, _ in deferred_foreign_keys()}
    inline = {}
    for child, col, parent, pcol in inline_foreign_keys():
        inline.setdefault(child, []).append((col, parent, pcol))
    out = [HEADER, "SET NAMES utf8mb4;\n",
           "-- Drop in one statement (checks off only for the DROP; data is loaded with checks on).\n",
           "SET FOREIGN_KEY_CHECKS = 0;\n",
           "DROP TABLE IF EXISTS " + ", ".join(q(t.name) for t in reversed(TABLES)) + ";\n",
           "SET FOREIGN_KEY_CHECKS = 1;\n"]
    for t in TABLES:
        lines = []
        for f in t.fields:
            null = "NOT NULL" if f.required else "NULL"
            note = f.description + (" [derived]" if f.derived else "") + (f" Units: {f.units}." if f.units else "")
            lines.append(f"  {q(f.name)} {column_type(f)} {null} COMMENT '{_sql_comment(note)}'")
        lines.append(f"  PRIMARY KEY ({q(t.pk)})")
        for f in t.fields:
            if f.unique and f.name != t.pk:
                lines.append(f"  UNIQUE KEY {q(ident('uq', t.name, f.name))} ({q(f.name)})")
        for combo in t.unique_together:
            lines.append(f"  UNIQUE KEY {q(ident('uq', t.name, *combo))} ({', '.join(q(c) for c in combo)})")
        for cols in INDEXES.get(t.name, []):
            lines.append(f"  KEY {q(ident('ix', t.name, *cols))} ({', '.join(q(c) for c in cols)})")
        for col, parent, pcol in inline.get(t.name, []):
            lines.append(f"  CONSTRAINT {q(ident('fk', t.name, col))} FOREIGN KEY ({q(col)}) "
                         f"REFERENCES {q(parent)} ({q(pcol)})")
        for f in t.fields:
            if (t.name, f.name) in deferred:
                lines.append(f"  KEY {q(ident('ix', t.name, f.name))} ({q(f.name)})")
            if f.enum:
                values = ", ".join(f"'{v}'" for v in f.enum)
                lines.append(f"  CONSTRAINT {q(ident('ck', t.name, f.name))} CHECK ({q(f.name)} IN ({values}))")
        for name, expr in TABLE_CHECKS.get(t.name, []):
            lines.append(f"  CONSTRAINT {q(ident('ck', t.name, name))} CHECK ({expr})")
        out.append(f"\n-- {t.entity} ({t.kind}): {t.description}\n")
        out.append(f"CREATE TABLE {q(t.name)} (\n" + ",\n".join(lines) +
                   f"\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='{_sql_comment(t.description[:2000])}';\n")
    return "".join(out)


def build_deferred_sql() -> str:
    out = [HEADER, "-- Forward-reference / circular foreign keys, added after the seed is loaded.\n",
           "-- MySQL validates every existing row when the constraint is added.\n"]
    for child, col, parent, pcol in deferred_foreign_keys():
        out.append(f"ALTER TABLE {q(child)} ADD CONSTRAINT {q(ident('fk', child, col))} "
                   f"FOREIGN KEY ({q(col)}) REFERENCES {q(parent)} ({q(pcol)});\n")
    return "".join(out)


def sql_literal(value: Any, ftype: str) -> str:
    if value is None:
        return "NULL"
    if ftype == "bool":
        return "1" if value else "0"
    if ftype == "int":
        return str(int(value))
    if ftype == "decimal":
        return f"{float(value):.2f}"
    if isinstance(value, datetime):
        return f"'{value.strftime('%Y-%m-%d %H:%M:%S')}'"
    if isinstance(value, date):
        return f"'{value.isoformat()}'"
    return "'" + str(value).replace("\\", "\\\\").replace("'", "''") + "'"


def build_seed_sql(tables: dict[str, list[dict]], label: str) -> str:
    out = [HEADER, f"-- Seed data: {label}\n", "SET NAMES utf8mb4;\n", "START TRANSACTION;\n"]
    for t in TABLES:
        rows = tables.get(t.name, [])
        out.append(f"\n-- {t.name}: {len(rows)} rows\n")
        cols = ", ".join(q(c) for c in t.columns)
        for i in range(0, len(rows), INSERT_BATCH):
            batch = rows[i:i + INSERT_BATCH]
            values = ",\n".join("(" + ", ".join(sql_literal(r.get(f.name), f.type) for f in t.fields) + ")" for r in batch)
            out.append(f"INSERT INTO {q(t.name)} ({cols}) VALUES\n{values};\n")
    out.append("COMMIT;\n")
    return "".join(out)


def split_statements(script: str) -> list[str]:
    """Split a script on ';' outside quotes, backticks and '--' comments (for driver-based loading)."""
    stmts, buf, i, n = [], [], 0, len(script)
    quote = None
    while i < n:
        ch = script[i]
        if quote:
            buf.append(ch)
            if ch == "\\" and quote == "'" and i + 1 < n:
                buf.append(script[i + 1])
                i += 2
                continue
            if ch == quote:
                if i + 1 < n and script[i + 1] == quote:   # doubled quote escape
                    buf.append(script[i + 1])
                    i += 2
                    continue
                quote = None
        elif ch in ("'", "`", '"'):
            quote = ch
            buf.append(ch)
        elif ch == "-" and script.startswith("--", i):
            j = script.find("\n", i)
            i = n if j == -1 else j + 1
            continue
        elif ch == ";":
            stmt = "".join(buf).strip()
            if stmt:
                stmts.append(stmt)
            buf = []
        else:
            buf.append(ch)
        i += 1
    tail = "".join(buf).strip()
    if tail:
        stmts.append(tail)
    return stmts
