"""Data dictionary and ER diagram, generated from orchestrator.schema (brief Step 1 / Step 9)."""

from __future__ import annotations

from orchestrator.ids import PATTERNS
from orchestrator.schema import RELATIONSHIPS, TABLES, deferred_foreign_keys

HEADER = "<!-- Generated by orchestrator.export.docs_writer from src/orchestrator/schema.py. Do not edit by hand. -->\n\n"


def _cell(text: str | None) -> str:
    return (text or "").replace("|", "\\|").replace("\n", " ")


def build_data_dictionary() -> str:
    deferred = {(c, col) for c, col, _, _ in deferred_foreign_keys()}
    out = [HEADER, "# Data dictionary\n\n",
           "Every table and field, generated from the schema used by the generator, the validator and the SQL DDL.\n",
           "Types: `str` VARCHAR, `int` INT, `decimal` DECIMAL(12,2), `bool` BOOLEAN, `date` DATE (YYYY-MM-DD), ",
           "`datetime` DATETIME (YYYY-MM-DD HH:MM:SS). **Derived** fields are computed from source records ",
           "(`generator/derive.py`), never generated independently.\n\n",
           "| Table | Entity | Kind | Primary key | Lifecycle |\n|---|---|---|---|---|\n"]
    for t in TABLES:
        out.append(f"| [`{t.name}`](#{t.name}) | {t.entity} | {t.kind} | `{t.pk}` | {_cell(t.lifecycle)} |\n")
    for t in TABLES:
        out.append(f"\n## {t.name}\n\n{t.description}\n\n")
        if t.lifecycle:
            out.append(f"Lifecycle: `{t.lifecycle}`\n\n")
        if t.unique_together:
            out.append("Unique together: " + ", ".join("(" + ", ".join(c) + ")" for c in t.unique_together) + "\n\n")
        out.append("| Field | Type | Required | Allowed values / format | Units | Unique | Key | Validation rule | Description |\n"
                   "|---|---|---|---|---|---|---|---|---|\n")
        for f in t.fields:
            allowed = ", ".join(f"`{v}`" for v in f.enum) if f.enum else (f"`{PATTERNS[f.pattern]}`" if f.pattern else "")
            key = "PK" if f.name == t.pk else ""
            if f.fk:
                key = (key + " " if key else "") + f"FK → `{f.fk}`" + (" (deferred)" if (t.name, f.name) in deferred else "")
            out.append(f"| `{f.name}` | {f.type}{f'({f.length})' if f.type == 'str' else ''} | "
                       f"{'yes' if f.required else 'no'} | {_cell(allowed)} | {_cell(f.units)} | "
                       f"{'yes' if f.unique or f.name == t.pk else ''} | {key} | {_cell(f.rule)} | "
                       f"{_cell(f.description)}{' **Derived.**' if f.derived else ''} |\n")
    return "".join(out)


def build_er_diagram() -> str:
    card = {"1:N": "||--o{", "1:0..1": "||--o|", "N:M": "}o--o{", "N:1": "}o--||"}
    out = [HEADER, "# Entity-relationship diagram\n\n", "```mermaid\nerDiagram\n"]
    for parent, child, c, note in RELATIONSHIPS:
        if child == "every entity":
            continue
        out.append(f'    {parent} {card[c]} {child} : "{note or c}"\n')
    out.append("```\n\n## Cardinality\n\n| Parent | Child | Cardinality | Note |\n|---|---|---|---|\n")
    for parent, child, c, note in RELATIONSHIPS:
        out.append(f"| `{parent}` | `{child}` | {c} | {_cell(note)} |\n")
    out.append("\nN:M relationships are resolved with bridge tables: `role_access_template` (Role ↔ AccessRole), "
               "`employee_role_history` (Employee ↔ Role over time), `task_dependency` (Task ↔ Task) and "
               "`asset_assignment` (Asset ↔ Employee over time). `audit_event` references any entity through "
               "`entity_type` + `entity_id`.\n")
    return "".join(out)
